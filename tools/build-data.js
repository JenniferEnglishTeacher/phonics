// Merges original rules + tools/new-rules.txt into phonics-data.js
// Usage: node tools/build-data.js  (reads tools/original-data.js)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(__dirname, "original-data.js"), "utf8");
const R = eval(src.replace("const PHONICS_RULES =", "(") .replace(/;\s*$/, ")"));

const HL = {
  "short-vowel-a": "a", "short-vowel-e": "e", "short-vowel-i": "i", "short-vowel-o": "o", "short-vowel-u": "u|oo",
  "long-vowel-a": "ai|ay|eigh|ey|ea|a", "long-vowel-e": "ee|ea|ie|ey|e", "long-vowel-i": "igh|ie|y|i",
  "long-vowel-o": "oa|ow|oe|o", "long-vowel-u": "ue|ew|ui|u",
  "ar-ar": "ar", "er-er": "er", "ir-er": "ir|ur", "or-or": "or",
  "au-aw-al": "au|aw|al", "ou-ow": "ou|ow", "oi-oy": "oi|oy",
  "bl-blend": "bl", "br-blend": "br", "cl-blend": "cl", "cr-blend": "cr", "pl-blend": "pl", "pr-blend": "pr",
  "sc-sk-blend": "sc|sk", "scr-blend": "scr", "sl-blend": "sl", "sm-blend": "sm", "sn-blend": "sn",
  "sp-blend": "sp", "st-blend": "st", "sw-blend": "sw",
  "ch": "ch", "ph-f": "ph", "sh": "sh", "th-voiced": "th", "th-voiceless": "th", "wh": "wh",
  "dge-d": "dge", "soft-c-s": "c(?=[eiy])", "soft-g-d": "g(?=[eiy])", "kn-n": "kn", "ng": "ng", "nk": "nk", "wr-r": "wr"
};
const MAGIC = { "long-vowel-a": "a", "long-vowel-e": "e", "long-vowel-i": "i", "long-vowel-o": "o", "long-vowel-u": "u" };

const GROUPS = [
  ["Short Vowels 短母音", ["short-vowel-a","short-vowel-e","short-vowel-i","short-vowel-o","short-vowel-u"]],
  ["Long Vowels 長母音", ["long-vowel-a","long-vowel-e","long-vowel-i","long-vowel-o","long-vowel-u"]],
  ["Long Vowel Teams 母音組合", ["ai-ay","ee-ea","oa-ow","ie-igh","ue-ew-ui","y-long-i","y-long-e"]],
  ["Other Vowel Sounds 其他母音", ["oo-long","oo-short","ea-short","au-aw-al","ou-ow","ow-two-sounds","oi-oy"]],
  ["R-Controlled Vowels 母音+r", ["ar-ar","er-er","ir-er","ur-er","or-or","ore-oar","air-are","ear-eer","war-wor"]],
  ["L-Blends", ["bl-blend","cl-blend","fl-blend","gl-blend","pl-blend","sl-blend"]],
  ["R-Blends", ["br-blend","cr-blend","dr-blend","fr-blend","gr-blend","pr-blend","tr-blend"]],
  ["S- & Other Blends", ["sc-sk-blend","sm-blend","sn-blend","sp-blend","st-blend","sw-blend","tw-blend"]],
  ["3-Letter Blends", ["scr-blend","spr-spl-blend","str-blend","qu-squ","thr-shr-blend"]],
  ["Final Blends 字尾子音", ["final-blends"]],
  ["Consonant Digraphs 子音組合", ["ch","sh","th-voiced","th-voiceless","wh","ph-f","ck","tch","ng","nk"]],
  ["Soft & Other Consonants", ["soft-c-s","soft-g-d","dge-d","x-ks","floss","all"]],
  ["Silent Letters 不發音字母", ["kn-n","wr-r","mb-silent-b","gn-silent-g","gh"]],
  ["Word Endings 字尾", ["le-ending","ed-ending","tion"]]
];

const byId = new Map(R.map(r => [r.id, { ...r, hl: HL[r.id], magic: MAGIC[r.id] }]));
const txt = fs.readFileSync(path.join(__dirname, "new-rules.txt"), "utf8").split(/\r?\n/);
let cur = null;
for (const line of txt) {
  if (!line.trim() || line.startsWith("# ")) continue;
  if (line.startsWith("## +")) { cur = byId.get(line.slice(4).trim()); if (!cur) throw line; continue; }
  if (line.startsWith("## ")) {
    const [id, title, sourceHeading, , ...hl] = line.slice(3).split(" | ").map(s => s.trim());
    cur = { id, title, sourceHeading, hl: hl.join(" | "), items: [] };
    byId.set(id, cur); continue;
  }
  const [word, pos, definition, sentence, translation] = line.split("|");
  if (!translation) throw new Error("bad line: " + line);
  if (!/_{3,}/.test(sentence)) throw new Error("no blank: " + line);
  cur.items.push({ word, pos, definition, sentence, translation, answer: word, id: word.toLowerCase() });
}

for (const r of byId.values()) for (const i of r.items) {
  const m = String(i.definition || "").match(/^\s*[,\/]\s*([A-Za-z.]+)\s+(.*)$/);
  if (m) { i.pos = `${i.pos}/${m[1]}`; i.definition = m[2]; }
  if (i.word === "Youtuber") i.definition = "YouTube 創作者";
  if (i.word === "north" && /注/.test(i.definition)) i.definition = "北方";
}
const out = [];
for (const [group, ids] of GROUPS) for (const id of ids) {
  const r = byId.get(id); if (!r) throw new Error("missing " + id);
  r.group = group; out.push(r); byId.delete(id);
}
if (byId.size) throw new Error("unplaced: " + [...byId.keys()]);
for (const r of out) {
  const seen = new Set();
  r.items = r.items.filter(i => { const k = i.word.toLowerCase().trim(); if (seen.has(k)) return false; seen.add(k); return true; });
  if (r.items.length < 12) console.warn("SHORT", r.id, r.items.length);
}
const body = "// Generated by tools/build-data.js\nconst PHONICS_RULES = " + JSON.stringify(out.map(({ id, title, sourceHeading, group, hl, magic, items }) => ({ id, title, sourceHeading, group, hl, magic, items: items.map(({ word, pos, definition, sentence, translation, answer }) => ({ word, pos, definition, sentence, translation, answer })) })), null, 1) + ";\n";
fs.writeFileSync(path.join(root, "phonics-data.js"), body);
console.log(out.length, "rules,", out.reduce((a, r) => a + r.items.length, 0), "words");
